# 4. Как установить необходимые пакеты внутрь виртуального окружения для
# conda/venv?
#     VENV: в venv мы в активированном venv прописываем pip install, которые нам
#     нужны или выгружаем все необходимые зависимости из requirements.txt
#     командой pip install -r requirements.txt
#     CONDA: в виртуальном окружении конды мы прописываем команду с заранее
#     подготовленным файлом conda env create -f environment.yml (прописывается 1
#     раз,с нуля), создастся ВО с соответствующими пакетами. Поштучно:
#     conda install package_name, и обновление (дополнение) пакетов с помощью
#     файла: conda env update -n env_name -f file.yml
