#   пайтону запустить модуль с названием venv)
#     1.1. Что делает каждая команда в списке ниже?
#         pip list - показывает зависимости текущего проекта и иъ версии
#         pip freeze > requirements.txt - фиксирует используемые в проекте
#         библиотеки в файл requirements.txt (знак > перенаправляет вывод в
#         текстовый файл)
#         pip install -r requirements.txt - устанавливает библиотеки, прописанные
#          в соответствующем файле (requirements.txt, -r - буквально означает
#          requirements)
#         Примечание: пип лист больше удобен и читаем для человека, а пип фриз -
#         для машины (хотя оба показывают список установленных пакетов).
# 2. Что делает каждая команда в списке ниже?
# conda env list - показывает список доступных (созданных) виртуальных окружений
# с помощью conda
# conda create -n env_name python=3.5 - создает виртуальное окружение с версией
# пайтона 3.5 (-n - флаг, отвечающий за имя (name))
# conda env update -n env_name -f file.yml - обновляет библиотеки и зависимости
# из файла file.yml (файл конфигурации со списком библиотек, аналог requirements.
# txt), если он был изменен. Примечание: флаг -f - указывает файл из которого
# берутся библиотеки проекта, -n - имя виртуального окружения.
# source activate env_name - эта команда активирует виртуальное окружение (unix
# like systems)
# source deactivate - деактивирует текущее (активное) виртуальное окружение
# conda clean -a - удаляет неиспользуемые и временные файлы (кэш, неиспользуемые
# библиотеки и их установщики). -a - флаг, который означает все (all)
# **Примечание:** source activate / source deactivate устарели: в современных
# версиях conda используются conda activate env_name и conda deactivate
